import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const source = await readFile(new URL('../../src/lib/sticker-randomizer.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const { StickerRandomizer } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
let counter = 0;
const randomizer = new StickerRandomizer(() => ++counter);
const still = { width: 640, height: 360, boxes: [{ originX: 240, originY: 100, width: 160, height: 180 }], expression: 'neutral', luminance: new Float32Array(576).fill(100) };
const first = randomizer.update(still, 0);
assert.equal(randomizer.update(still, 300), first);
assert.equal(randomizer.update({ ...still, boxes: [{ ...still.boxes[0], originX: 241 }] }, 400), first, 'ignore subpixel detector noise');
assert.equal(randomizer.update({ ...still, luminance: new Float32Array(576).fill(110) }, 500), first, 'ignore uniform exposure changes');
const shifted = { ...still, boxes: [{ ...still.boxes[0], originX: 255 }] };
const moved = randomizer.update(shifted, 600);
assert.notEqual(moved, first, 'face translation reshuffles');
const smiling = randomizer.update({ ...shifted, expression: 'smiling' }, 601);
assert.notEqual(smiling, moved, 'expression change bypasses movement interval');
const neutral = randomizer.update(shifted, 602);
assert.notEqual(neutral, smiling, 'smiling to neutral also reshuffles immediately');
const pixels = new Float32Array(576).fill(100);
pixels.fill(180, 0, 100);
const gesture = randomizer.update({ ...shifted, luminance: pixels }, 900);
assert.notEqual(gesture, neutral, 'body/hand motion reshuffles even with a stationary face');
assert.equal(randomizer.update({ ...shifted, luminance: pixels }, 1100), gesture);
assert.notEqual(randomizer.update({ ...shifted, luminance: pixels }, 3000), gesture, 'periodic variety still works');
console.log('Motion, gestures, both expression changes, jitter suppression, and periodic shuffle checks passed.');
